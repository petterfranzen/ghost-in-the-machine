#!/usr/bin/env bash
# Songbranch — build a static dist/ from the Go module and the three web files.
# Everything the page needs is in dist/: no fonts, no CDNs, no requests at all
# except the page itself. Run ./build.sh then open dist/index.html.
set -euo pipefail

cd "$(dirname "$0")"
ROOT=$(pwd)
DIST="$ROOT/dist"

export CGO_ENABLED=0
export GOOS=js
export GOARCH=wasm

echo "→ building the module"
rm -rf "$DIST" .build
mkdir -p "$DIST" .build
go build -trimpath -buildvcs=false -ldflags="-s -w -buildid=" -o .build/game.wasm ./cmd/wasm

WASM_EXEC="$(go env GOROOT)/lib/wasm/wasm_exec.js"
if [ ! -f "$WASM_EXEC" ]; then
  WASM_EXEC="$(go env GOROOT)/misc/wasm/wasm_exec.js"
fi
if [ ! -f "$WASM_EXEC" ]; then
  echo "could not find wasm_exec.js in the Go tree" >&2
  exit 1
fi

echo "→ writing dist/wasm.js ($(du -h .build/game.wasm | cut -f1) module)"
{
  echo "/* Songbranch — generated by build.sh. Go's wasm_exec.js, then the module"
  echo " * as base64. Do not edit; run ./build.sh instead. */"
  cat "$WASM_EXEC"
  printf '\nconst WASM_B64 = "'
  base64 .build/game.wasm | tr -d "\n"
  printf '";\n'
  cat tools/boot.js
} > "$DIST/wasm.js"

cp src/index.html src/style.css src/app.js "$DIST/"

# --- checks the build itself must pass -------------------------------------
echo "→ checking the output"
grep -q 'id="stage"' "$DIST/index.html"
grep -q './wasm.js' "$DIST/index.html"
grep -q './app.js' "$DIST/index.html"
grep -q 'pointerdown' "$DIST/app.js"
grep -q 'requestAnimationFrame' "$DIST/app.js"
grep -q 'songbranchHold' "$DIST/app.js"
grep -q 'songbranchSwipe' "$DIST/app.js"
grep -q 'aria-pressed="false"' "$DIST/index.html"
grep -q 'prefers-reduced-motion' "$DIST/style.css"
grep -q 'prefers-reduced-motion' "$DIST/app.js"
grep -q 'WASM_B64' "$DIST/wasm.js"
node --check "$DIST/app.js"
node --check "$DIST/wasm.js"
[ "$(find "$DIST" -type f | wc -l)" -eq 4 ]

# --- the smoke test runs the real module in node ----------------------------
node tools/smoke.mjs .build/game.wasm "$WASM_EXEC"

echo "→ dist/: $(find "$DIST" -type f | wc -l) files, $(du -sh "$DIST" | cut -f1)"
