// Inline the wasm module into a plain script, so the page works from file://
// (no server, no fetch, no MIME worries) as well as from GitHub Pages.
import { readFileSync, writeFileSync } from 'node:fs';

const [, , src, out] = process.argv;
const bytes = readFileSync(src);
const b64 = bytes.toString('base64');
writeFileSync(
  out,
  `// generated by tools/embed.mjs from ${src} — ${bytes.length} bytes\n` +
    `const WASM_B64 = "${b64}";\n`
);
console.log(`embedded ${bytes.length} bytes -> ${out} (${b64.length} b64 chars)`);
